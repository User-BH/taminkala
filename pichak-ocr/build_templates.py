#!/usr/bin/env python3
"""Build captcha_templates.py from labelled real captchas, and measure accuracy.

    python3 build_templates.py samples/            # build + leave-one-out report
    python3 build_templates.py samples/ --check    # report only, do not write

samples/labels.json maps file name -> expression, e.g. {"captcha-01.jpg": "86+1"}.
More (and more varied) samples => better templates. Add new samples whenever
the OCR abstains often, then rebuild and copy captcha_templates.py to /opt/pichak.

Designed by Rahvar Peyvand Dadeh (شرکت رهوار پیوند داده).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
import captcha_math_ocr as ocr  # noqa: E402

GLYPHS = {"plus": "+", "eq": "=", "q": "?"}


def load(folder: Path):
    labels = json.loads((folder / "labels.json").read_text(encoding="utf-8"))
    out = []
    for name, expr in sorted(labels.items()):
        a, b = expr.split("+")
        if len(a) != 2 or len(b) != 1:
            print(f"skip {name}: only the 'NN+N' layout is supported ({expr})")
            continue
        out.append((name, expr, ocr.text_mask(Image.open(folder / name))))
    return out


def cells(mask, expr, ox=0, oy=0):
    a, b = expr.split("+")
    chars = {"d1": a[0], "d2": a[1], "d3": b, **GLYPHS}
    for slot, ch in chars.items():
        yield ch, ocr.crop(mask, ocr.BASE_X + ox + ocr.LAYOUT[slot], ocr.BASE_Y + oy)


def build(samples, offsets=None):
    acc = {}
    for i, (_, expr, mask) in enumerate(samples):
        ox, oy = offsets[i] if offsets else (0, 0)
        for ch, cell in cells(mask, expr, ox, oy):
            acc.setdefault(ch, []).append(cell)
    templates = {}
    for ch, group in acc.items():
        templates[ch] = ["".join(str(round(9 * sum(c[y][x] for c in group) / len(group)))
                                 for x in range(ocr.CELL_W)) for y in range(ocr.CELL_H)]
    return templates


def build_aligned(samples):
    """Two passes: build at the nominal position, then re-align each sample."""
    first = build(samples)
    offsets = [ocr.locate(mask, first)[1:3] for _, _, mask in samples]
    return build(samples, offsets)


def leave_one_out(samples):
    right = wrong = abstain = 0
    for i, (name, expr, _) in enumerate(samples):
        if len(samples) < 2:
            break
        templates = build_aligned(samples[:i] + samples[i + 1:])
        result, details = ocr.recognize(Image.open(FOLDER / name), templates)
        if result is None:
            abstain += 1
            verdict = f"abstain ({details.get('reason')})"
        elif result["expression"] == expr:
            right += 1
            verdict = "ok"
        else:
            wrong += 1
            verdict = f"WRONG -> {result['expression']}"
        print(f"  {name:18} {expr:6} {verdict:24} anchors={details['anchors']} digits={details['digits']}")
    n = len(samples)
    print(f"\nleave-one-out on {n}: correct={right}  abstained={abstain}  wrong={wrong}")
    return wrong


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    FOLDER = Path(sys.argv[1])
    data = load(FOLDER)
    leave_one_out(data)
    if "--check" not in sys.argv:
        templates = build_aligned(data)
        target = Path(__file__).resolve().parent / "captcha_templates.py"
        body = ",\n".join(f"    {ch!r}: [\n" + "".join(f"        {row!r},\n" for row in rows) + "    ]"
                          for ch, rows in sorted(templates.items()))
        target.write_text(
            '"""Glyph templates for captcha_math_ocr — generated by build_templates.py; do not edit.\n\n'
            f'Built from {len(data)} labelled captchas. Each digit 0-9 is how often that pixel is ink.\n"""\n'
            f"TEMPLATES = {{\n{body}\n}}\n", encoding="utf-8")
        print(f"wrote {target.name} ({len(templates)} glyphs: {''.join(sorted(templates))})")
